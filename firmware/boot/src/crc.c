uint16_t boot_crc16(const uint8_t *data, size_t len) {
  uint16_t crc = 0xFFFFu;
  for (size_t i = 0; i < len; ++i) {
    crc = (uint16_t)((crc << 8) ^ kCrc16Table[((crc >> 8) ^ data[i]) & 0xFFu]);
  }
  return crc;
}

/* The table above is built MSB-first, so folding is crc = table[(crc ^ byte) & 0xFF] ^
 * (crc >> 8) with the 0xEDB88320 reflected polynomial — the table already contains the
 * reflected form, which is why no reflection appears in the loop. */
uint32_t boot_crc32(const uint8_t *data, size_t len) {
  uint32_t crc = 0xFFFFFFFFu;
  for (size_t i = 0; i < len; ++i) {
    crc = kCrc32Table[(crc ^ data[i]) & 0xFFu] ^ (crc >> 8);
  }
  return crc ^ 0xFFFFFFFFu;
}